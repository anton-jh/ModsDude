using ModsDude.Client.Core.Exceptions;
using ModsDude.Client.Core.GameAdapters.DynamicForms;
using ModsDude.Client.Core.Helpers;
using ModsDude.Client.Core.Models;
using System.Globalization;
using System.Xml;
using System.Xml.Linq;

namespace ModsDude.Client.Core.GameAdapters.Implementations.FarmingSimulatorV1;

public class FarmingSimulatorBaseSavegameAdapter : IBaseSavegameAdapter
{
    /// <summary>
    /// Farming Simulator has a fixed set of numbered folders and no way to add another, so a save
    /// always fills or displaces one that is already there.
    /// </summary>
    public bool CanCreateSlots => false;


    public IInstanceSavegameAdapter WithInstanceSettings(string serializedInstanceSettings)
    {
        var instanceSettings = FarmingSimulatorInstanceSettings.Deserialize(serializedInstanceSettings);
        instanceSettings.EnsureValid();
        return new FarmingSimulatorInstanceSavegameAdapter(instanceSettings);
    }

    public IInstanceSavegameAdapter WithInstanceSettings(DynamicForm instanceSettings)
    {
        if (instanceSettings is not FarmingSimulatorInstanceSettings settings)
        {
            throw new IncorrectGameAdapterSettingsTypeException<FarmingSimulatorInstanceSettings>(instanceSettings);
        }
        settings.EnsureValid();
        return new FarmingSimulatorInstanceSavegameAdapter(settings);
    }
}


public class FarmingSimulatorInstanceSavegameAdapter(FarmingSimulatorInstanceSettings instanceSettings)
    : FarmingSimulatorBaseSavegameAdapter, IInstanceSavegameAdapter
{
    /// <summary>
    /// The game offers this many slots and no more. A number about one game, which is exactly why it
    /// lives here and why <see cref="IInstanceSavegameAdapter.GetSlots"/> hands back a list - nothing
    /// above this file has to know it.
    /// </summary>
    private const int _slotCount = 20;

    /// <summary>
    /// The file every started save has, and the only one read to describe a slot. Its absence is how
    /// an empty slot is told from an occupied one.
    /// </summary>
    private const string _careerSavegameFile = "careerSavegame.xml";

    /// <summary>
    /// Regenerated by the game from the save beside it, so it is bulk that would make every check-in
    /// bigger and make the content hash differ for a reason nobody played.
    /// </summary>
    private static readonly string[] _excludedFileNames = ["screenshot.png"];


    private string GameDataFolder => instanceSettings.GameDataFolder
        ?? throw new InvalidOperationException("Instance settings carry no game data folder.");


    public string GetSlotPath(SavegameSlotId slot)
    {
        return Path.Combine(GameDataFolder, slot.Value);
    }

    /// <summary>
    /// Every slot, in the order the game numbers them.
    /// </summary>
    /// <remarks>
    /// Read in parallel, capped the way the mod scan is: this is disk bound, so a handful at a time
    /// is as quick as twenty, and the thread pool belongs to the rest of the app too. Indexed rather
    /// than collected, so the results keep the slot order rather than the order they finished in.
    /// </remarks>
    public Task<IReadOnlyList<SavegameSlot>> GetSlots(CancellationToken cancellationToken)
    {
        return Task.Run<IReadOnlyList<SavegameSlot>>(() =>
        {
            var slots = new SavegameSlot[_slotCount];

            var options = new ParallelOptions
            {
                MaxDegreeOfParallelism = Environment.ProcessorCount,
                CancellationToken = cancellationToken
            };

            Parallel.For(0, _slotCount, options, i =>
            {
                var id = new SavegameSlotId($"savegame{i + 1}");
                slots[i] = ReadSlot(id, GetSlotPath(id), cancellationToken);
            });

            return slots;
        }, cancellationToken);
    }

    public bool BelongsInPackedSave(string relativePath)
    {
        return !_excludedFileNames.Contains(Path.GetFileName(relativePath), StringComparer.OrdinalIgnoreCase);
    }


    /// <summary>
    /// One slot, described from its career file.
    /// </summary>
    /// <remarks>
    /// <b>Degrades rather than throws</b>, and always in the same direction. A slot whose career file
    /// is missing is empty; one whose career file will not parse, or that a running game is writing,
    /// is <b>occupied and unnamed</b>. Reporting it as empty is the single mistake that matters here,
    /// because an empty slot is the one the engine writes to without asking.
    /// </remarks>
    private static SavegameSlot ReadSlot(SavegameSlotId id, string slotPath, CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();

        var careerFile = Path.Combine(slotPath, _careerSavegameFile);

        if (!File.Exists(careerFile))
        {
            return new SavegameSlot(id, null, false, null, null);
        }

        var lastModified = File.GetLastWriteTime(careerFile);

        var maybeSettings = ReadCareerSettings(careerFile);
        if (maybeSettings.HasValue is false)
        {
            return new SavegameSlot(id, null, true, lastModified, null);
        }

        var settings = maybeSettings.Value;

        var name =
            from element in Maybe.From(settings.Element("savegameName"))
            let value = element.Value.Trim()
            where string.IsNullOrWhiteSpace(value) is false
            select value;

        var playtime =
            from element in Maybe.From(settings.Element("playTime"))
            from minutes in ParseMinutes(element.Value)
            select minutes;

        return new SavegameSlot(
            id,
            name.HasValue ? name.Value : null,
            true,
            lastModified,
            playtime.HasValue ? playtime.Value : null);
    }

    /// <summary>
    /// Playtime is minutes, as an invariant decimal. Anything else is a layout this adapter does not
    /// know, and an unreadable playtime costs a column rather than a slot.
    /// </summary>
    private static Maybe<TimeSpan> ParseMinutes(string value)
    {
        return double.TryParse(value, NumberStyles.Float, CultureInfo.InvariantCulture, out var minutes)
            ? TimeSpan.FromMinutes(minutes)
            : Maybe<TimeSpan>.None;
    }

    /// <summary>
    /// None for a career file that cannot be read as one - which is not an error here, only an
    /// unnamed slot. A game that is mid-write holds the file, and a save from a version this adapter
    /// does not know may not carry the element at all.
    /// </summary>
    private static Maybe<XElement> ReadCareerSettings(string careerFile)
    {
        try
        {
            var settings = new XmlReaderSettings
            {
                DtdProcessing = DtdProcessing.Prohibit,
                XmlResolver = null
            };

            using var reader = XmlReader.Create(careerFile, settings);

            return
                from document in Maybe.From(XDocument.Load(reader))
                from root in Maybe.From(document.Element("careerSavegame"))
                from element in Maybe.From(root.Element("settings"))
                select element;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or XmlException)
        {
            return Maybe<XElement>.None;
        }
    }
}
