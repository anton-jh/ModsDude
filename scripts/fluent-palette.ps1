<#
.SYNOPSIS
    Regenerates FluentPalette.xaml, which points WPF's Fluent dark theme at the app's own palette.

.DESCRIPTION
    The Fluent theme builds each of its ~500 brushes from a handful of colours, but binds them with
    StaticResource inside its own dictionary, so redefining a colour after it changes nothing. The
    brushes themselves have to be redefined. This reads the theme's source for the given WPF release,
    keeps every brush built from a colour in the map below, and writes it out again built from the
    palette colour instead. The colours the theme reads dynamically are aliased as well.

    Run it after changing the map or moving to a new WPF release, and commit the result. The palette
    itself is Palette.xaml; this only decides which of the theme's colours become which of ours.

.PARAMETER WpfTag
    The dotnet/wpf tag to read the theme from. Match the WindowsDesktop runtime the client ships on.
#>
[CmdletBinding()]
param(
    [string]$WpfTag = 'v10.0.15'
)

$ErrorActionPreference = 'Stop'

$map = [ordered]@{
    'TextFillColorPrimary'               = 'TextPrimaryColor'
    'TextFillColorSecondary'             = 'TextSecondaryColor'
    'TextFillColorTertiary'              = 'TextMutedColor'
    'TextFillColorDisabled'              = 'TextDisabledColor'
    'AccentTextFillColorDisabled'        = 'TextDisabledColor'
    'TextOnAccentFillColorPrimary'       = 'OnAccentColor'
    'TextOnAccentFillColorSecondary'     = 'OnAccentSecondaryColor'
    'TextOnAccentFillColorSelectedText'  = 'OnAccentColor'
    'TextOnAccentFillColorDisabled'      = 'TextDisabledColor'
    'SystemAccentColor'                  = 'AccentColor'
    'SystemAccentColorLight1'            = 'AccentColor'
    'SystemAccentColorLight2'            = 'AccentColor'
    'SystemAccentColorLight3'            = 'AccentTextColor'
    'SystemAccentColorDark1'             = 'AccentColor'
    'SystemAccentColorDark2'             = 'AccentColor'
    'SystemAccentColorDark3'             = 'AccentColor'
    'ApplicationBackgroundColor'         = 'WindowColor'
    'AcrylicBackgroundFillColorDefault'  = 'PopupColor'
    'SolidBackgroundFillColorBase'       = 'WindowColor'
    'SolidBackgroundFillColorSecondary'  = 'ShellColor'
    'SolidBackgroundFillColorTertiary'   = 'ContentColor'
    'SolidBackgroundFillColorQuarternary' = 'CardColor'
    'ControlFillColorInputActive'        = 'InsetColor'
    'SystemFillColorSuccess'             = 'SuccessColor'
    'SystemFillColorCaution'             = 'CautionColor'
    'SystemFillColorCritical'            = 'CriticalColor'
    'SystemFillColorSuccessBackground'   = 'SuccessTintColor'
    'SystemFillColorCautionBackground'   = 'CautionTintColor'
    'SystemFillColorCriticalBackground'  = 'CriticalTintColor'
}

$repoRoot = Split-Path -Parent $PSScriptRoot
$outputPath = Join-Path $repoRoot 'ModsDude.Client/ModsDude.Client.Wpf/Shared/Resources/FluentPalette.xaml'
$sourceUrl = "https://raw.githubusercontent.com/dotnet/wpf/$WpfTag/src/Microsoft.DotNet.Wpf/src/Themes/PresentationFramework.Fluent/Themes/Fluent.Dark.xaml"

$source = (Invoke-WebRequest -Uri $sourceUrl -UseBasicParsing).Content
$document = [xml]$source
$xamlNamespace = 'http://schemas.microsoft.com/winfx/2006/xaml'
$staticReference = [regex]'\{StaticResource (\w+)\}'
$dynamicReference = [regex]'\{DynamicResource (\w+)\}'

function Get-MappedReferences([System.Xml.XmlNode]$node) {
    $staticReference.Matches($node.OuterXml) | ForEach-Object { $_.Groups[1].Value } | Where-Object { $map.Contains($_) }
}

function Set-MappedReferences([System.Xml.XmlNode]$node) {
    foreach ($attribute in @($node.Attributes)) {
        $attribute.Value = $staticReference.Replace($attribute.Value, {
            param($match)
            $key = $match.Groups[1].Value
            if ($map.Contains($key)) { "{StaticResource $($map[$key])}" } else { $match.Value }
        })
    }
    foreach ($child in @($node.ChildNodes)) {
        if ($child.NodeType -eq [System.Xml.XmlNodeType]::Element) { Set-MappedReferences $child }
    }
}

$brushes = foreach ($node in $document.DocumentElement.ChildNodes) {
    if ($node.NodeType -ne [System.Xml.XmlNodeType]::Element) { continue }
    if ($node.LocalName -notin 'SolidColorBrush', 'LinearGradientBrush') { continue }
    if (-not (Get-MappedReferences $node)) { continue }
    $copy = $node.CloneNode($true)
    Set-MappedReferences $copy
    $copy
}

$dynamicKeys = $dynamicReference.Matches($source) |
    ForEach-Object { $_.Groups[1].Value } |
    Where-Object { $map.Contains($_) } |
    Sort-Object -Unique

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('<!-- Generated by scripts/fluent-palette.ps1 from the Fluent dark theme of dotnet/wpf ' + $WpfTag + '. Do not edit:')
$lines.Add('     change the map in the script, or the colours in Palette.xaml, and run it again. -->')
$lines.Add('<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"')
$lines.Add('                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">')
$lines.Add('')
$lines.Add('    <ResourceDictionary.MergedDictionaries>')
$lines.Add('        <ResourceDictionary Source="Palette.xaml" />')
$lines.Add('    </ResourceDictionary.MergedDictionaries>')
$lines.Add('')

foreach ($key in $dynamicKeys) {
    $lines.Add("    <DynamicResource x:Key=""$key"" ResourceKey=""$($map[$key])"" />")
}
$lines.Add('')

$settings = [System.Xml.XmlWriterSettings]::new()
$settings.OmitXmlDeclaration = $true
$settings.Indent = $true
$settings.IndentChars = '    '
$settings.ConformanceLevel = [System.Xml.ConformanceLevel]::Fragment

foreach ($brush in ($brushes | Sort-Object { $_.GetAttribute('Key', $xamlNamespace) })) {
    $builder = [System.Text.StringBuilder]::new()
    $writer = [System.Xml.XmlWriter]::Create($builder, $settings)
    $brush.WriteTo($writer)
    $writer.Flush()
    $text = $builder.ToString() -replace ' xmlns(:\w+)?="[^"]*"', ''
    foreach ($line in ($text -split "`r?`n")) {
        $lines.Add("    $line")
    }
}

$lines.Add('</ResourceDictionary>')

$encoding = [System.Text.UTF8Encoding]::new($false)
[System.IO.File]::WriteAllText($outputPath, (($lines -join "`r`n") + "`r`n"), $encoding)
Write-Host "Wrote $($brushes.Count) brushes and $($dynamicKeys.Count) aliases to $outputPath"
