<#
.SYNOPSIS
    Regenerates _Palette.cshtml, which gives the server's account and admin pages the client's palette.

.DESCRIPTION
    Reads the client's Palette.xaml and writes every colour, brush and corner radius in it as a CSS
    custom property, named after its key in kebab case without the Color, Brush or CornerRadius suffix
    (TextPrimaryColor becomes --text-primary, CardCornerRadius becomes --card-radius). A brush built
    from a colour of the same name is left out; one built from another colour refers to it. Brushes
    whose key does not end in Brush belong to the WPF theme and are left out too.

    Run it after changing Palette.xaml, and commit the result.
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
$sourcePath = Join-Path $repoRoot 'ModsDude.Client/ModsDude.Client.Wpf/Shared/Resources/Palette.xaml'
$outputPath = Join-Path $repoRoot 'ModsDude.Server/ModsDude.Server.Api/Shared/_Palette.cshtml'
$xamlNamespace = 'http://schemas.microsoft.com/winfx/2006/xaml'
$staticReference = [regex]'^\{StaticResource (\w+)\}$'

function ConvertTo-PropertyName([string]$key, [string]$suffix) {
    $stem = $key.Substring(0, $key.Length - $suffix.Length)
    '--' + ([regex]::Replace($stem, '(?<=[a-z0-9])(?=[A-Z])', '-')).ToLowerInvariant()
}

function ConvertTo-CssColor([string]$value) {
    if ($value -match '^#([0-9A-Fa-f]{2})([0-9A-Fa-f]{6})$') {
        return "#$($Matches[2])$($Matches[1])".ToUpperInvariant()
    }
    if ($value -match '^#[0-9A-Fa-f]{6}$') {
        return $value.ToUpperInvariant()
    }
    throw "Unsupported colour '$value' in $sourcePath."
}

function ConvertTo-CssRadius([string]$value) {
    ($value.Trim() -split '[\s,]+' | ForEach-Object { if ($_ -eq '0') { '0' } else { "${_}px" } }) -join ' '
}

$document = [xml](Get-Content -Raw -Path $sourcePath)
$properties = [ordered]@{}

function Add-Property([string]$name, [string]$value) {
    if ($properties.Contains($name)) {
        throw "Two keys in $sourcePath both become $name."
    }
    $properties[$name] = $value
}

foreach ($node in $document.DocumentElement.ChildNodes) {
    if ($node.NodeType -ne [System.Xml.XmlNodeType]::Element) { continue }
    $key = $node.GetAttribute('Key', $xamlNamespace)

    switch ($node.LocalName) {
        'Color' {
            Add-Property (ConvertTo-PropertyName $key 'Color') (ConvertTo-CssColor $node.InnerText.Trim())
        }
        'SolidColorBrush' {
            if (-not $key.EndsWith('Brush')) { continue }
            $name = ConvertTo-PropertyName $key 'Brush'
            $color = $node.GetAttribute('Color')
            $reference = $staticReference.Match($color)
            if (-not $reference.Success) {
                Add-Property $name (ConvertTo-CssColor $color)
                continue
            }
            $referenced = ConvertTo-PropertyName $reference.Groups[1].Value 'Color'
            if ($referenced -ne $name) {
                Add-Property $name "var($referenced)"
            }
        }
        'CornerRadius' {
            Add-Property ((ConvertTo-PropertyName $key 'CornerRadius') + '-radius') (ConvertTo-CssRadius $node.InnerText)
        }
        default {
            throw "Unsupported resource <$($node.LocalName) x:Key=""$key""> in $sourcePath. Teach this script to convert it."
        }
    }
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('@* Generated by scripts/web-palette.ps1 from the client''s Palette.xaml. Do not edit:')
$lines.Add('   change the colours in Palette.xaml and run it again. *@')
$lines.Add('<style>')
$lines.Add('    :root {')
foreach ($entry in $properties.GetEnumerator()) {
    $lines.Add("        $($entry.Key): $($entry.Value);")
}
$lines.Add('    }')
$lines.Add('</style>')

$newLine = [Environment]::NewLine
$encoding = [System.Text.UTF8Encoding]::new($false)
[System.IO.File]::WriteAllText($outputPath, (($lines -join $newLine) + $newLine), $encoding)
Write-Host "Wrote $($properties.Count) properties to $outputPath"
